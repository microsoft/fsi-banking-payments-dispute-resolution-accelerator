function deriveDescription(merchantName: string | undefined, reasonCodeLabel: string | undefined, transactionAmount: number | undefined, cardholderName?: string): string {
  const merchant = merchantName || 'the merchant';
  const amount = typeof transactionAmount === 'number' ? `$${transactionAmount.toFixed(2)}` : 'a transaction';
  const label = (reasonCodeLabel || 'the submitted dispute').toLowerCase();
  const actor = cardholderName || 'The customer';
  return `${actor} submitted a dispute for ${amount} with ${merchant}, citing ${label}.`;
}

